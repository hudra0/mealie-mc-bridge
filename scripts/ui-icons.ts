// The children of the <svg> element, on one line.
export function innerSvg(source: string): string {
  const open = source.indexOf(">", source.indexOf("<svg"));
  const close = source.lastIndexOf("</svg>");
  if (open < 0 || close < 0) throw new Error("not an SVG document");
  return source
    .slice(open + 1, close)
    .replace(/\s*\n\s*/g, "")
    .replace(/\s+\/>/g, "/>")
    .trim();
}

export function generate(read: (name: string) => string): string {
  const lines = ICON_NAMES.map((name) => `  "${name}": ${JSON.stringify(innerSvg(read(name)))},`);
  return [
    "// Generated by scripts/ui-icons.ts from lucide-static; do not edit by hand.",
    "// Lucide icons, ISC License, Copyright (c) Lucide Icons and Contributors; some derived",
    "// from Feather, MIT License, Copyright (c) 2013-present Cole Bemis. See",
    "// THIRD_PARTY_NOTICES.md.",
    "",
    "export const ICONS = {",
    ...lines,
    "} as const;",
    "",
    "export type IconName = keyof typeof ICONS;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const require = createRequire(import.meta.url);
  const dir = path.join(path.dirname(require.resolve("lucide-static/package.json")), "icons");
  const target = fileURLToPath(new URL("../src/service/ui/icons.generated.ts", import.meta.url));
  writeFileSync(
    target,
    generate((name) => readFileSync(path.join(dir, `${name}.svg`), "utf8")),
  );
  console.log(`wrote ${ICON_NAMES.length} icons to ${path.relative(process.cwd(), target)}`);
}
