// Builds the corpus-derived parts of a locale pack, knowledge/locales/<locale>/, from the
// corpus of that locale (npm run corpus:analyze -- --locale <locale>):
//
//   ingredient-catalog.json  generated in full (build-ingredient-catalog.ts)
//   units.json               pieceWeights.items and the "corpus" section: the unit spellings,
//                            group names and serving units official recipes use, as a table
//                            for writing the vocabulary by hand
//   phrases.json             the "corpus" section: the short text steps official recipes
//                            repeat most, as evidence for the standard phrases
//
// Everything else in units.json and phrases.json, and mc.json, technique-aliases.json and
// prompt-rules.md, is written by hand; the build keeps it as it is. A pack file that does
// not exist yet starts with the generated parts only.
//
// The frequent text steps are standard device phrases ("Insert the measuring beaker into the
// lid."): official recipes use each in at least MIN_PHRASE_RECIPES recipes, numbers become
// <n> and nothing longer than MAX_PHRASE_LENGTH characters is kept. No recipe text beyond
// such phrases leaves the corpus.
//
// No file I/O here: build-knowledge.ts calls these builders and writes the results.

import type { IngredientsAnalysis } from "./build-timing-units.js";
import { pieceWeightItems } from "./build-timing-units.js";
import type { NormalizedStep } from "./types.js";

export const MIN_PHRASE_RECIPES = 10;
export const MAX_PHRASE_LENGTH = 72;
export const MAX_PHRASES = 40;

type Json = Record<string, unknown>;

interface CountEntry {
  key: string;
  count: number;
}

// Top entries of an analyzer count list ([{key: "\"g\"", count}]) as {spelling: count}.
function topCounts(entries: readonly CountEntry[] | undefined, limit: number): Json {
  const out: Json = {};
  for (const entry of (entries ?? []).slice(0, limit)) {
    const key = entry.key.startsWith('"') ? String(JSON.parse(entry.key)) : entry.key;
    out[key] = entry.count;
  }
  return out;
}

function topRecord(record: Readonly<Record<string, number>> | undefined, limit: number): Json {
  return Object.fromEntries(
    Object.entries(record ?? {})
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
      .slice(0, limit),
  );
}

// The piece concept of the analyzer is German ("Stück"); a pack writes it in its language.
function pieceLabel(existing: Json | null): (concept: string) => string {
  const vocabulary = Array.isArray(existing?.vocabulary)
    ? (existing.vocabulary as { concept?: string; singular?: string }[])
    : [];
  const piece = vocabulary.find((entry) => entry.concept === "piece")?.singular;
  return (concept) => (concept === "Stück" && piece ? piece : concept);
}

// units.json of a pack: the hand-written fields of `existing` with the piece weights and the
// corpus tables refreshed.
export function buildPackUnits(
  locale: string,
  ingredients: IngredientsAnalysis,
  existing: Json | null,
): Json {
  const analysis = ingredients as unknown as {
    meta?: { recipes?: number; official?: number };
    units?: { bySource?: { official?: { ingredients?: number; unitExact?: CountEntry[] } } };
    groups?: { official?: { normalized?: CountEntry[] } };
    servings?: { units?: Record<string, number> }[];
  };
  const official = analysis.units?.bySource?.official;
  const corpus = {
    note: "Generated by npm run corpus:build-knowledge from the corpus of this locale: unit spellings, group names and serving units of official recipes, with counts. Evidence for the hand-written vocabulary, not read by the converter.",
    recipes: analysis.meta?.recipes ?? 0,
    officialRecipes: analysis.meta?.official ?? 0,
    officialIngredientRows: official?.ingredients ?? 0,
    unitSpellings: topCounts(official?.unitExact, 15),
    groupNames: topCounts(analysis.groups?.official?.normalized, 12),
    servingUnits: topRecord(analysis.servings?.[0]?.units, 8),
  };
  const base: Json = existing ?? {
    description: `Unit vocabulary and unit rules for ${locale}. Fill in the hand-written fields; see CONTRIBUTING.md, "Adding a language".`,
    locale,
  };
  const pieceWeights = (base.pieceWeights as Json | undefined) ?? {
    note: "Grams per piece or package from weights stated in the corpus. Entries with at least 4 observations.",
  };
  return {
    ...base,
    pieceWeights: { ...pieceWeights, items: pieceWeightItems(ingredients, pieceLabel(existing)) },
    corpus,
  };
}

// The short text steps official recipes repeat most, numbers as <n>.
export function frequentTextSteps(steps: readonly NormalizedStep[]): {
  textSteps: number;
  phrases: { text: string; recipes: number }[];
} {
  const recipes = new Map<string, Set<number>>();
  let textSteps = 0;
  for (const step of steps) {
    if (step.kind !== "text" || step.source !== "official") continue;
    textSteps++;
    const text = (step.text ?? "").replace(/\s+/g, " ").trim();
    if (text === "" || text.length > MAX_PHRASE_LENGTH) continue;
    const key = text.replace(/\d+(?:[.,]\d+)?/g, "<n>");
    const seen = recipes.get(key) ?? new Set<number>();
    seen.add(step.recipeId);
    recipes.set(key, seen);
  }
  const phrases = [...recipes.entries()]
    .map(([text, ids]) => ({ text, recipes: ids.size }))
    .filter((entry) => entry.recipes >= MIN_PHRASE_RECIPES)
    .sort((a, b) => b.recipes - a.recipes || a.text.localeCompare(b.text))
    .slice(0, MAX_PHRASES);
  return { textSteps, phrases };
}

// phrases.json of a pack: the hand-written fields of `existing` with the corpus section
// refreshed.
export function buildPackPhrases(
  locale: string,
  steps: readonly NormalizedStep[],
  existing: Json | null,
): Json {
  const { textSteps, phrases } = frequentTextSteps(steps);
  const base: Json = existing ?? {
    description: `Standard phrases and step-text words for ${locale}. Fill in the hand-written fields; see CONTRIBUTING.md, "Adding a language".`,
    locale,
  };
  return {
    ...base,
    corpus: {
      note: `Generated by npm run corpus:build-knowledge: the short text steps (at most ${MAX_PHRASE_LENGTH} characters, numbers as <n>) that official recipes of this locale repeat in at least ${MIN_PHRASE_RECIPES} recipes. Evidence for the standard phrases above, not read by the converter.`,
      officialTextSteps: textSteps,
      frequentTextSteps: phrases,
    },
  };
}
